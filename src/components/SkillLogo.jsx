const fallbackColors = ['#7c3aed', '#0284c7', '#059669', '#db2777', '#d97706', '#4f46e5'];

export default function SkillLogo({ name, index = 0 }) {
  const [failed, setFailed] = useState(false);
  const brand = skillBrands[name];
  const initials = name.replace(/[^a-z0-9 ]/gi, ' ').trim().split(/\s+/).slice(0, 2).map((part) => part[0]).join('').toUpperCase();
  const color = brand ? `#${brand[1]}` : fallbackColors[index % fallbackColors.length];

  return (
    <span className={`skill-logo${brand && !failed ? ' has-brand-logo' : ''}`} style={{ '--skill-logo-color': color }} role="img" aria-label={`${name} logo`}>
      {brand && !failed
        ? <img src={`https://cdn.simpleicons.org/${brand[0]}/${brand[1]}`} alt="" onError={() => setFailed(true)} />
        : <span aria-hidden="true">{initials}</span>}
    </span>
  );
}
